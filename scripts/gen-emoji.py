"""Writes app/src/emojiTable.h for the emoji picker (step 4.2): the single emoji of Unicode's
emoji-test.txt that HyperBerry's font has, in the file's groups. A single emoji is one code point,
with or without U+FE0F; sequences (skin tones, ZWJ, keycaps, flag pairs) are left out (user,
2026-10-29). Written fully qualified, so with the FE0F the line has.

Run by hand to refresh the table, after fetch-emoji.sh, in the image it builds:
    docker run --rm -v "$PWD:/src" hyperberry-font python -I /src/scripts/gen-emoji.py \\
        /src/build/emoji/emoji-test.txt /src/app/assets/fonts/HyperBerryEmoji.ttf /src/app/src/emojiTable.h
"""
import sys

from fontTools.ttLib import TTFont

# The emoji drawn in the strip for each group; Recent's (U+1F558) isn't in the table.
ICONS = {
    "Smileys & Emotion": "\U0001F600", "People & Body": "\U0001F44B", "Animals & Nature": "\U0001F43B",
    "Food & Drink": "\U0001F354", "Travel & Places": "\U0001F697", "Activities": "⚽",
    "Objects": "\U0001F4A1", "Symbols": "\U0001F523", "Flags": "\U0001F3C1",
}


def main(src, font, dst):
    cmap = TTFont(font).getBestCmap()
    groups = {}  # insertion-ordered: the file's order
    for line in open(src, encoding="utf-8"):
        if line.startswith("# group: "):
            group = line[9:].strip()
        elif line[:1] not in ("#", "\n") and line.split(";")[1].split("#")[0].strip() == "fully-qualified":
            cps = [int(c, 16) for c in line.split(";")[0].split()]
            if group != "Component" and len(cps) <= 2 and (len(cps) == 1 or cps[1] == 0xFE0F) and cps[0] in cmap:
                groups.setdefault(group, []).append("".join(map(chr, cps)))
    count = sum(len(v) for v in groups.values())
    assert 1300 <= count <= 1450, count
    everything = set("".join("".join(v) for v in groups.values()))
    assert set(ICONS) == set(groups) and all(i in everything or ord(i) in cmap for i in ICONS.values())
    with open(dst, "w", encoding="utf-8") as out:
        out.write("// Generated by scripts/gen-emoji.py from emoji-test.txt (Unicode 18.0); don't edit.\n"
                  "// Each group: its title and its emoji, UTF-8, separated by spaces.\n"
                  "#ifndef EMOJITABLE_H\n#define EMOJITABLE_H\n\n"
                  "struct EmojiGroup\n{\n    const char *title;\n    const char *icon;\n    const char *emoji;\n};\n\n"
                  "static const EmojiGroup kEmojiTable[] = {\n")
        for title, items in groups.items():
            out.write('    { "%s", "%s",\n      "%s" },\n' % (title, ICONS[title], " ".join(items)))
        out.write("};\n\n#endif\n")
    print("%s: %d groups, %d emoji" % (dst, len(groups), count))


if __name__ == "__main__":
    main(*sys.argv[1:])
