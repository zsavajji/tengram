"""Writes app/assets/countries.js for the linking page's country picker (step 2.3): every region
libphonenumber knows, with its calling code, its national prefix (the 0 of "07911…" that goes
after +44; Italy keeps its 0, so it has none), its names in English and Italian, and whether
it's the main region of its code (US for +1, RU for +7, GB for +44).

Run by hand to refresh the data, in a pinned image:
    docker run --rm -v "$PWD:/src" python:3.12-slim@sha256:aa943ce411423c7582288f18707ff66eddcbaeb510502d747a72aeb34f30d159 \\
        sh -c 'pip install -q --root-user-action=ignore phonenumbers==9.0.42 &&
               python -I /src/scripts/gen-countries.py /src/app/assets/countries.js'
"""
import json
import sys

import phonenumbers
from phonenumbers import COUNTRY_CODE_TO_REGION_CODE, PhoneMetadata
from phonenumbers.geodata.locale import LOCALE_DATA

HEAD = """.pragma library
// Generated by scripts/gen-countries.py from libphonenumber (phonenumbers %s); don't edit.
// [region, calling code, national prefix, English name, Italian name, main region of its code]
var data = [
"""


# Regions the table has no names for.
MISSING = {
    "AC": {"en": "Ascension Island", "it": "Isola di Ascensione"},
    "TA": {"en": "Tristan da Cunha", "it": "Tristan da Cunha"},
    "XK": {"en": "Kosovo", "it": "Kosovo"},
}


def name(names, lang):
    """The name in lang; the table writes "*xx" for "the same as in language xx"."""
    v = names.get(lang)
    while v and v.startswith("*"):
        v = names.get(v[1:])
    return v


def main(out):
    rows = []
    for code, regions in COUNTRY_CODE_TO_REGION_CODE.items():
        for i, region in enumerate(regions):
            if region == "001":  # non-geographic numbers (+800, +882…)
                continue
            md = PhoneMetadata.metadata_for_region(region)
            names = MISSING.get(region) or LOCALE_DATA.get(region, {})
            rows.append([region, code, (md.national_prefix if md else None) or "",
                         name(names, "en") or region, name(names, "it") or name(names, "en") or region,
                         1 if i == 0 else 0])
    rows.sort(key=lambda r: r[3])
    with open(out, "w", encoding="utf-8") as f:
        f.write(HEAD % phonenumbers.__version__)
        f.write(",\n".join(json.dumps(r, ensure_ascii=False) for r in rows))
        f.write("\n]\n")
    print(len(rows), "regions")


if __name__ == "__main__":
    main(sys.argv[1])
